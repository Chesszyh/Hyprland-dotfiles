#!/usr/bin/env python3
import argparse
import json
import re
from pathlib import Path

HOME = Path.home()
ROOT = HOME / ".config" / "dark-angel"
STATE_ROOT = HOME / ".local" / "state" / "dark-angel"
CACHE_ROOT = HOME / ".cache" / "dark-angel"

PALETTE = ROOT / "palette.json"
CURRENT = STATE_ROOT / "current"
QML_COLORS = STATE_ROOT / "qml_color.json"
HYPR_COLORS = STATE_ROOT / "hypr.conf"
HYPR_LUA = STATE_ROOT / "hypr.lua"
ROFI_THEME = CACHE_ROOT / "rofi.rasi"
SWAYNC_STYLE = CACHE_ROOT / "swaync.css"

REQUIRED = {
    "mode",
    "background",
    "surface",
    "surfaceAlt",
    "surfaceElevated",
    "primary",
    "secondary",
    "accent",
    "error",
    "text",
    "textMuted",
    "border",
    "shadow",
    "glow",
}
HEX_RE = re.compile(r"^#[0-9A-Fa-f]{6}$")


def load_palette() -> dict:
    data = json.loads(PALETTE.read_text(encoding="utf-8"))
    if set(data) != {"light", "dark"}:
        raise SystemExit("palette must contain exactly light and dark")
    for name, theme in data.items():
        missing = REQUIRED - set(theme)
        extra = set(theme) - REQUIRED
        if missing or extra:
            raise SystemExit(f"{name} token mismatch missing={missing} extra={extra}")
        if theme["mode"] != name:
            raise SystemExit(f"{name}.mode must be {name}")
        for key, value in theme.items():
            if key != "mode" and (not isinstance(value, str) or not HEX_RE.match(value)):
                raise SystemExit(f"{name}.{key} must be #RRGGBB")
    return data


def read_current() -> str:
    if CURRENT.exists():
        mode = CURRENT.read_text(encoding="utf-8").strip()
        if mode in {"light", "dark"}:
            return mode
    return "dark"


def resolve_mode(requested: str) -> str:
    if requested == "toggle":
        return "light" if read_current() == "dark" else "dark"
    return requested


def no_hash(color: str) -> str:
    return color.removeprefix("#")


def rgba(color: str, alpha: float) -> str:
    raw = no_hash(color)
    r = int(raw[0:2], 16)
    g = int(raw[2:4], 16)
    b = int(raw[4:6], 16)
    return f"rgba({r}, {g}, {b}, {alpha:.2f})"


def qml_color(theme: dict) -> str:
    data = {
        "windowBackground": theme["background"],
        "primaryText": theme["text"],
        "layerBackground1": theme["surface"],
        "layerBackground2": theme["surfaceAlt"],
        "layerBackground3": theme["surfaceElevated"],
        "surfaceText": theme["text"],
        "secondaryText": theme["textMuted"],
        "borderPrimary": theme["border"],
        "shadowColor": theme["shadow"],
        "accentPrimary": theme["primary"],
        "accentSecondary": theme["secondary"],
        "selectionBackground": theme["glow"],
        "accentPrimaryText": theme["background"],
        "selectionText": theme["text"],
        "borderSecondary": theme["border"],
    }
    return json.dumps(data, indent=2) + "\n"


def hypr_conf(theme: dict) -> str:
    return f"""# Generated by ~/.config/dark-angel/scripts/apply-theme.py. Do not edit by hand.
$dark_angel_mode = {theme["mode"]}
$dark_angel_background = rgb({no_hash(theme["background"])})
$dark_angel_surface = rgb({no_hash(theme["surface"])})
$dark_angel_primary = rgb({no_hash(theme["primary"])})
$dark_angel_secondary = rgb({no_hash(theme["secondary"])})
$dark_angel_accent = rgb({no_hash(theme["accent"])})
$dark_angel_text = rgb({no_hash(theme["text"])})
$dark_angel_border = rgb({no_hash(theme["border"])})
$dark_angel_glow = rgb({no_hash(theme["glow"])})

$color10 = rgb({no_hash(theme["border"])})
$color11 = rgb({no_hash(theme["secondary"])})
$color12 = rgb({no_hash(theme["primary"])})
$color13 = rgb({no_hash(theme["accent"])})
$color14 = rgb({no_hash(theme["glow"])})
$color15 = rgb({no_hash(theme["text"])})
"""


def hypr_lua(theme: dict) -> str:
    colors = {
        "color10": theme["border"],
        "color11": theme["secondary"],
        "color12": theme["primary"],
        "color13": theme["accent"],
        "color14": theme["glow"],
        "color15": theme["text"],
    }
    lines = ["return {"]
    lines.extend(f'  {name} = "rgb({no_hash(value)})",' for name, value in colors.items())
    lines.append("}")
    return "\n".join(lines) + "\n"


def rofi_theme(theme: dict) -> str:
    return f"""/* Generated by ~/.config/dark-angel/scripts/apply-theme.py. */
* {{
    font: "LXGW WenKai 13";
    background: {rgba(theme["background"], 0.88)};
    background-alt: {rgba(theme["surface"], 0.82)};
    foreground: {theme["text"]};
    selected: {theme["primary"]};
    active: {theme["secondary"]};
    urgent: {theme["error"]};
    border-color: {rgba(theme["border"], 0.70)};
}}
"""


def swaync_style(theme: dict) -> str:
    return f"""/* Generated by ~/.config/dark-angel/scripts/apply-theme.py. */
@define-color noti-bg {rgba(theme["background"], 0.84)};
@define-color noti-bg-alt {rgba(theme["surface"], 0.76)};
@define-color noti-bg-hover {rgba(theme["surfaceElevated"], 0.82)};
@define-color noti-border-color {rgba(theme["border"], 0.62)};
@define-color text-color {theme["text"]};
@define-color muted-text {theme["textMuted"]};
@define-color cc-primary {theme["primary"]};
@define-color cc-secondary {theme["secondary"]};
"""


def write(path: Path, content: str, dry_run: bool) -> None:
    if dry_run:
        print(f"would write {path}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"wrote {path}")


def apply(mode: str, dry_run: bool) -> None:
    palette = load_palette()
    resolved = resolve_mode(mode)
    theme = palette[resolved]

    write(QML_COLORS, qml_color(theme), dry_run)
    write(HYPR_COLORS, hypr_conf(theme), dry_run)
    write(HYPR_LUA, hypr_lua(theme), dry_run)
    write(ROFI_THEME, rofi_theme(theme), dry_run)
    write(SWAYNC_STYLE, swaync_style(theme), dry_run)
    write(CURRENT, resolved + "\n", dry_run)


def main() -> int:
    parser = argparse.ArgumentParser(description="Apply Dark Angel light/dark theme")
    parser.add_argument("mode", choices=("light", "dark", "toggle"))
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    apply(args.mode, args.dry_run)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
